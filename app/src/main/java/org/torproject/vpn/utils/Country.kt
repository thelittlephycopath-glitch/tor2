        }
    }

    companion object {
        private const val TAG = "Country"

        fun fromCode(code: String?): Country? {
            if (code.isNullOrEmpty() || code.length != 2) {
                Log.e(TAG, "$code is an invalid country code")
                return null
            }

            val countryCodeCaps = code.uppercase()
            if (!countryCodeCaps[0].isLetter() || !countryCodeCaps[1].isLetter()) {
                return null
            }

            return entries.find { it.code == countryCodeCaps }
        }
    }
